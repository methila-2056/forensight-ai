"""Segment-level classifier (Phase 9b) — supervised window classification.

This is a **separate concern from Strategy A anomaly detection**
(`engines/ml/anomaly.py`), and the distinction matters:

* Strategy A is **unsupervised**. It asks "does this window deviate from this
  case's own typical activity?" and produces a continuous anomaly score.
* This classifier is **supervised**. It asks "what kind of activity segment is
  this, given labelled examples?" and produces one of a small set of labels.

The two are never presented as the same number. A window can be anomalous
within its own case yet classified ``benign`` against the training set, and
that disagreement is meaningful rather than contradictory.

Honesty contract
----------------
Training data is **entirely synthetic**, generated by
``demo/generate_scenarios.py``. Every metric this module produces describes
performance on that synthetic data and nothing else. It says nothing about any
real environment, and the mandatory label below travels with every stored
metric and every API response so a figure can never be quoted without its
caveat. There are no real-world performance claims.

Labels are derived from **scenario provenance**, not from the rule engine or
from anomaly scores. Using rule output as a label would only re-learn the rules;
using anomaly score as a label would inherit its unsupervised thresholds.

Label vocabulary
----------------
``benign``            ordinary activity (including the pre-anchor portion of a
                      compromise scenario)
``compromise``        post-anchor activity in an account-compromise scenario
``ransomware_like``   impact windows in the ransomware-like scenario

Determinism: fixed seed, fixed feature order, fixed window size, fixed split,
single-threaded. Re-running on the same corpora reproduces identical metrics.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Optional

from app import config

# Mandatory label. Travels with every stored metric and API response.
SYNTHETIC_LABEL = "Trained and evaluated on synthetic demonstration data."
NO_REAL_WORLD_CLAIM = (
    "Metrics describe performance on synthetic demonstration data only. They are "
    "not a statement about any real environment and require investigator validation."
)

LABELS = ("benign", "compromise", "ransomware_like")
MODEL_VERSION = "segment-classifier-v1"
WINDOW_MINUTES = 10  # distinct from Strategy A's 5-minute windows, by design

# Smallest number of labelled windows per class before a stratified split is
# attempted at all. Below this the split is not meaningful, so the module
# abstains and says so rather than reporting a metric from a handful of rows.
MIN_WINDOWS_PER_CLASS = 8


@dataclass
class LabelledWindow:
    """One window plus the label its scenario provenance assigns to it."""

    window_start: datetime
    window_end: datetime
    features: dict[str, int]
    label: str
    scenario: str


@dataclass
class ClassifierMetrics:
    """Evaluation result. Every field describes synthetic-data performance."""

    model_name: str = MODEL_VERSION
    dataset_desc: str = ""
    split_desc: str = ""
    accuracy: Optional[float] = None
    precision: Optional[float] = None
    recall: Optional[float] = None
    f1: Optional[float] = None
    # Per-class scores plus a confusion matrix, all synthetic-data figures.
    per_class: dict = field(default_factory=dict)
    confusion_matrix: list = field(default_factory=list)
    baseline_accuracy: Optional[float] = None
    cv_accuracy_mean: Optional[float] = None
    cv_accuracy_std: Optional[float] = None
    cv_folds: int = 0
    feature_list: list = field(default_factory=list)
    window_count: int = 0
    class_counts: dict = field(default_factory=dict)
    abstained: bool = False
    abstained_reason: Optional[str] = None
    synthetic_label: str = SYNTHETIC_LABEL
    disclaimer: str = NO_REAL_WORLD_CLAIM

    def as_dict(self) -> dict:
        return {
            "model_name": self.model_name,
            "dataset_desc": self.dataset_desc,
            "split_desc": self.split_desc,
            "accuracy": self.accuracy,
            "precision": self.precision,
            "recall": self.recall,
            "f1": self.f1,
            "per_class": self.per_class,
            "confusion_matrix": self.confusion_matrix,
            "baseline_accuracy": self.baseline_accuracy,
            "cv_accuracy_mean": self.cv_accuracy_mean,
            "cv_accuracy_std": self.cv_accuracy_std,
            "cv_folds": self.cv_folds,
            "feature_list": self.feature_list,
            "window_count": self.window_count,
            "class_counts": self.class_counts,
            "abstained": self.abstained,
            "abstained_reason": self.abstained_reason,
            "synthetic_label": self.synthetic_label,
            "disclaimer": self.disclaimer,
        }


# ---------------------------------------------------------------------------
# Scenario provenance -> labels
# ---------------------------------------------------------------------------
#
# Each incident corpus declares an anchor timestamp: the moment the synthetic
# incident begins. Windows before it are ordinary activity in the same
# environment; windows at or after it are the incident's effect. Anchors are
# declared here rather than inferred, because inferring them from the rule
# engine would make the labels depend on the thing we are trying to measure.

@dataclass(frozen=True)
class ScenarioSpec:
    key: str
    label_after_anchor: str
    anchor: datetime
    description: str


SCENARIO_SPECS: tuple[ScenarioSpec, ...] = (
    ScenarioSpec(
        key="A",
        label_after_anchor="benign",
        anchor=datetime(2099, 1, 1),  # never reached: scenario A has no incident
        description="benign control (routine office activity)",
    ),
    ScenarioSpec(
        key="B",
        label_after_anchor="compromise",
        anchor=datetime(2026, 10, 6, 22, 2),
        description="account compromise (login burst + scripting + exfiltration)",
    ),
    ScenarioSpec(
        key="C",
        label_after_anchor="ransomware_like",
        anchor=datetime(2026, 10, 7, 2, 10),
        description="ransomware-like (mass modification + rename burst)",
    ),
)


def spec_for(scenario_key: str) -> Optional[ScenarioSpec]:
    for spec in SCENARIO_SPECS:
        if spec.key == scenario_key.upper():
            return spec
    return None


def label_for_window(spec: ScenarioSpec, window_end: datetime) -> str:
    """Provenance label for one window: benign before the anchor, incident after."""
    return "benign" if window_end <= spec.anchor else spec.label_after_anchor


# ---------------------------------------------------------------------------
# Feature vector
# ---------------------------------------------------------------------------


def window_vector(
    window, *, feature_names: tuple[str, ...] | None = None
) -> list[float]:
    """Fixed-order numeric vector for one FeatureWindow.

    Derived features (rates, breadth ratios, entropy) are added on top of the
    raw 18 counts used by Strategy A, so the classifier sees shape rather than
    just volume. Order is fixed; `feature_list` records it alongside the metrics.
    """
    counts = dict(window.features)
    names = feature_names or tuple(sorted(counts))
    total = float(sum(counts.values())) or 1.0

    vector: list[float] = [float(counts.get(name, 0)) for name in names]

    # Volume-normalised proportions (what mix of activity this is).
    for name in names:
        vector.append(counts.get(name, 0) / total)

    # Breadth and intensity ratios.
    users = counts.get("distinct_users", 0)
    hosts = counts.get("distinct_hosts", 0)
    vector.extend(
        [
            float(users),
            float(hosts),
            float(counts.get("distinct_source_ips", 0)),
            float(counts.get("distinct_file_paths", 0)),
            float(counts.get("distinct_processes", 0)),
            (users / hosts) if hosts else 0.0,
            total / max(1, hosts),
            float(counts.get("src_file_activity", 0)) / total,
            float(counts.get("src_network", 0)) / total,
            float(counts.get("src_authentication", 0)) / total,
            float(counts.get("src_process", 0)) / total,
            float(counts.get("high_severity_count", 0)) + float(
                counts.get("critical_severity_count", 0)
            ),
            float(counts.get("duplicate_count", 0)),
            float(total),
        ]
    )
    return vector


def classifier_feature_names(base_names: tuple[str, ...]) -> list[str]:
    """The fixed feature order, recorded with the metrics for reproducibility."""
    names = [f"count:{n}" for n in base_names]
    names += [f"share:{n}" for n in base_names]
    names += [
        "distinct_users",
        "distinct_hosts",
        "distinct_source_ips",
        "distinct_file_paths",
        "distinct_processes",
        "users_per_host",
        "events_per_host",
        "share_file_activity",
        "share_network",
        "share_authentication",
        "share_process",
        "high_or_critical_count",
        "duplicate_count",
        "total_events",
    ]
    return names


# ---------------------------------------------------------------------------
# Training and evaluation
# ---------------------------------------------------------------------------


def evaluate(windows: list[LabelledWindow], *, seed: int | None = None) -> ClassifierMetrics:
    """Train and evaluate the classifier on labelled synthetic windows.

    Abstains (reporting *why*) when the labelled set is too small or too
    imbalanced for a stratified split to mean anything. Reporting a metric
    computed from three rows would be worse than reporting nothing.
    """
    seed = config.RANDOM_STATE if seed is None else seed
    metrics = ClassifierMetrics()

    metrics.window_count = len(windows)
    if not windows:
        metrics.abstained = True
        metrics.abstained_reason = "no labelled windows available"
        return metrics

    counts: dict[str, int] = {}
    for w in windows:
        counts[w.label] = counts.get(w.label, 0) + 1
    metrics.class_counts = dict(sorted(counts.items()))
    metrics.feature_list = classifier_feature_names(
        tuple(sorted(windows[0].features.keys()))
    )

    # Every label must be present, and present often enough to split.
    missing = [label for label in LABELS if label not in counts]
    if missing:
        metrics.abstained = True
        metrics.abstained_reason = (
            f"no windows labelled {', '.join(missing)}; the labelled set does not "
            "cover the label vocabulary"
        )
        return metrics

    rare = {k: v for k, v in counts.items() if v < MIN_WINDOWS_PER_CLASS}
    if rare:
        metrics.abstained = True
        detail = ", ".join(f"{k}={v}" for k, v in sorted(rare.items()))
        metrics.abstained_reason = (
            f"too few windows for a stratified split ({detail}); minimum is "
            f"{MIN_WINDOWS_PER_CLASS} per class"
        )
        return metrics

    # Imbalance guard: a single class must not swamp the rest.
    total = sum(counts.values())
    if max(counts.values()) / total > 0.8:
        metrics.abstained = True
        metrics.abstained_reason = (
            "labelled set is too imbalanced for a meaningful stratified split "
            f"(largest class is {max(counts.values())}/{total} of windows)"
        )
        return metrics

    from sklearn.ensemble import RandomForestClassifier
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import (
        accuracy_score,
        classification_report,
        confusion_matrix,
        f1_score,
        precision_score,
        recall_score,
    )
    from sklearn.model_selection import StratifiedKFold, train_test_split
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler

    x = [window_vector(w, feature_names=tuple(sorted(w.features.keys()))) for w in windows]
    y = [w.label for w in windows]

    metrics.dataset_desc = (
        f"synthetic incident corpora A/B/C, {WINDOW_MINUTES}-minute windows, "
        f"{len(windows)} windows ({', '.join(f'{k}={v}' for k, v in sorted(counts.items()))}); "
        "labels from scenario provenance"
    )

    # Stratified hold-out.
    x_train, x_test, y_train, y_test = train_test_split(
        x, y, test_size=0.25, random_state=seed, stratify=y
    )
    metrics.split_desc = (
        f"stratified 75/25 hold-out (seed {seed}), n_train={len(x_train)}, "
        f"n_test={len(x_test)}"
    )

    model = RandomForestClassifier(
        n_estimators=200, random_state=seed, class_weight="balanced"
    )
    model.fit(x_train, y_train)
    predicted = model.predict(x_test)

    metrics.accuracy = float(accuracy_score(y_test, predicted))
    metrics.precision = float(
        precision_score(y_test, predicted, average="macro", zero_division=0)
    )
    metrics.recall = float(recall_score(y_test, predicted, average="macro", zero_division=0))
    metrics.f1 = float(f1_score(y_test, predicted, average="macro", zero_division=0))
    metrics.confusion_matrix = confusion_matrix(
        y_test, predicted, labels=list(LABELS)
    ).tolist()
    metrics.per_class = classification_report(
        y_test, predicted, labels=list(LABELS), output_dict=True, zero_division=0
    )

    # Majority-class baseline: the honest comparator. A classifier that does
    # not beat this has learned nothing worth reporting.
    majority = max(counts.values()) / total
    metrics.baseline_accuracy = float(majority)

    # Cross-validation for a less split-dependent figure.
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    scores = []
    for train_index, test_index in skf.split(x, y):
        fold = RandomForestClassifier(
            n_estimators=200, random_state=seed, class_weight="balanced"
        )
        fold.fit([x[i] for i in train_index], [y[i] for i in train_index])
        scores.append(
            float(accuracy_score([y[i] for i in test_index], fold.predict([x[i] for i in test_index])))
        )
    metrics.cv_folds = len(scores)
    metrics.cv_accuracy_mean = float(sum(scores) / len(scores))
    metrics.cv_accuracy_std = float(
        (sum((s - metrics.cv_accuracy_mean) ** 2 for s in scores) / len(scores)) ** 0.5
    )

    return metrics


def fit_predict(
    windows: list[LabelledWindow], *, seed: int | None = None
) -> Optional[tuple[list[tuple[str, float]], ClassifierMetrics]]:
    """Train on all labelled windows, then score the same windows in-sample.

    In-sample scores are labelled as such. Out-of-sample figures come from
    `evaluate`; this exists so the UI can show *what label the model assigns*
    to each window, which is a prediction, not a performance claim.
    """
    from sklearn.ensemble import RandomForestClassifier

    seed = config.RANDOM_STATE if seed is None else seed
    metrics = evaluate(windows, seed=seed)
    if metrics.abstained:
        return None, metrics

    x = [window_vector(w, feature_names=tuple(sorted(w.features.keys()))) for w in windows]
    y = [w.label for w in windows]
    model = RandomForestClassifier(
        n_estimators=200, random_state=seed, class_weight="balanced"
    )
    model.fit(x, y)

    probabilities = model.predict_proba(x)
    classes = list(model.classes_)
    out: list[tuple[str, float]] = []
    for row in probabilities:
        best = max(range(len(classes)), key=lambda i: row[i])
        out.append((classes[best], float(row[best])))
    return out, metrics


